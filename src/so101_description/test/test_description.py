"""
Checks that the generated SO-101 description stays faithful to upstream.

The xacro macro is generated by tools/generate_xacro.py; these tests fail if
it drifts from urdf/upstream/so101_new_calib.urdf in kinematics, inertia or
limits, or if the simulation-specific changes listed in meshes/SOURCE.md go
missing.
"""

import math
from pathlib import Path
import xml.etree.ElementTree as ET

import pytest
import xacro

PKG = Path(__file__).resolve().parents[1]
UPSTREAM = ET.parse(PKG / 'urdf' / 'upstream' / 'so101_new_calib.urdf').getroot()
ROBOT = ET.fromstring(xacro.process_file(str(PKG / 'urdf' / 'so101.urdf.xacro')).toxml())

ACTUATED = ('shoulder_pan', 'shoulder_lift', 'elbow_flex', 'wrist_flex', 'wrist_roll',
            'gripper')
ADDED_LINKS = {'world', 'grasp_link'}
ADDED_JOINTS = {'so101_mount', 'grasp_joint'}


def floats(text):
    return [float(v) for v in text.split()]


def by_name(root, tag):
    return {e.get('name'): e for e in root.findall(tag)}


UP_JOINTS, JOINTS = by_name(UPSTREAM, 'joint'), by_name(ROBOT, 'joint')
UP_LINKS, LINKS = by_name(UPSTREAM, 'link'), by_name(ROBOT, 'link')


def test_same_links_and_joints_as_upstream_plus_additions():
    assert set(LINKS) == set(UP_LINKS) | ADDED_LINKS
    assert set(JOINTS) == set(UP_JOINTS) | ADDED_JOINTS


@pytest.mark.parametrize('name', sorted(UP_JOINTS))
def test_joint_kinematics_match_upstream(name):
    ours, theirs = JOINTS[name], UP_JOINTS[name]
    assert ours.get('type') == theirs.get('type')
    for attr in ('xyz', 'rpy'):
        assert floats(ours.find('origin').get(attr)) == pytest.approx(
            floats(theirs.find('origin').get(attr)))
    assert ours.find('parent').get('link') == theirs.find('parent').get('link')
    assert ours.find('child').get('link') == theirs.find('child').get('link')
    if theirs.get('type') == 'revolute':
        assert floats(ours.find('axis').get('xyz')) == floats(theirs.find('axis').get('xyz'))
        for bound in ('lower', 'upper'):
            assert float(ours.find('limit').get(bound)) == float(theirs.find('limit').get(bound))


@pytest.mark.parametrize('name', ACTUATED)
def test_servo_limits_and_dynamics(name):
    joint = JOINTS[name]
    assert float(joint.find('limit').get('effort')) == 2.94
    assert float(joint.find('limit').get('velocity')) == 4.7
    assert float(joint.find('dynamics').get('damping')) == 0.6
    assert float(joint.find('dynamics').get('friction')) == 0.052


@pytest.mark.parametrize('name', sorted(UP_LINKS))
def test_inertials_match_upstream(name):
    ours, theirs = LINKS[name].find('inertial'), UP_LINKS[name].find('inertial')
    assert float(ours.find('mass').get('value')) == float(theirs.find('mass').get('value'))
    assert floats(ours.find('origin').get('xyz')) == floats(theirs.find('origin').get('xyz'))
    for key in ('ixx', 'ixy', 'ixz', 'iyy', 'iyz', 'izz'):
        assert float(ours.find('inertia').get(key)) == float(theirs.find('inertia').get(key))


@pytest.mark.parametrize('name', sorted(UP_LINKS))
def test_visual_meshes_match_upstream_and_exist(name):
    ours = LINKS[name].findall('visual')
    theirs = UP_LINKS[name].findall('visual')
    assert len(ours) == len(theirs)
    for a, b in zip(ours, theirs):
        mesh = a.find('geometry/mesh').get('filename')
        assert Path(mesh).name == Path(b.find('geometry/mesh').get('filename')).name
        assert mesh.startswith('file://') and Path(mesh[len('file://'):]).is_file()
        assert floats(a.find('origin').get('xyz')) == floats(b.find('origin').get('xyz'))


@pytest.mark.parametrize('name', sorted(n for n in UP_LINKS if UP_LINKS[n].find('visual')
                                        is not None))
def test_collision_geometry_is_boxes_only(name):
    collisions = LINKS[name].findall('collision')
    assert collisions, f'{name} has no collision geometry'
    for collision in collisions:
        assert collision.find('geometry/box') is not None
        assert collision.find('geometry/mesh') is None


def test_jaws_have_pads():
    # The fixed jaw is part of gripper_link: body box plus a finger pad.
    assert len(LINKS['gripper_link'].findall('collision')) == 2
    pad = LINKS['moving_jaw_so101_v1_link'].find('collision')
    # Tilted so it closes flat on a 3 cm piece (spec section 2).
    assert floats(pad.find('origin').get('rpy')) == pytest.approx([0.0, 0.0, -0.25])


def test_grasp_link_sits_between_the_jaws():
    joint = JOINTS['grasp_joint']
    assert joint.find('parent').get('link') == 'gripper_frame_link'
    x, y, z = floats(joint.find('origin').get('xyz'))
    # gripper_frame_link is on the fixed jaw's inner face; the moving jaw is
    # on its -x side.
    assert -0.03 < x < -0.01 and y == 0.0 and -0.01 < z <= 0.0


def test_colours_use_the_industrial_scheme():
    colours = {m.get('name'): floats(m.find('color').get('rgba'))
               for m in ROBOT.findall('material') if m.find('color') is not None}
    assert colours['3d_printed'][:3] == [1.0, 0.45, 0.0]
    assert colours['sts3215'][:3] == [0.2, 0.2, 0.22]


def test_no_ros1_transmissions():
    assert ROBOT.find('transmission') is None


def test_generator_output_is_committed():
    """The committed macro must be what the generator produces today."""
    import subprocess
    import sys
    generated = subprocess.run(
        [sys.executable, str(PKG / 'tools' / 'generate_xacro.py')],
        capture_output=True, text=True, check=True).stdout
    assert generated == (PKG / 'urdf' / 'so101_macro.xacro').read_text()


def test_masses_are_plausible():
    total = sum(float(link.find('inertial/mass').get('value'))
                for link in LINKS.values() if link.find('inertial') is not None)
    # The real follower arm weighs a little over half a kilogram.
    assert 0.4 < total < 0.8
    assert not math.isnan(total)
